import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { getConnection } from "../config/db.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const migrationsDir = path.join(__dirname, "../db/migrations");

async function migrate() {
  let connection;

  try {
    console.log("🔄 Starting database migration...");

    connection = await getConnection();

    console.log("✅ Connected to Oracle database");

    // Create migration tracking table if it doesn't exist
    await connection.execute(`
      BEGIN
        EXECUTE IMMEDIATE '
          CREATE TABLE DB_MIGRATIONS (
            ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            NAME VARCHAR2(255) NOT NULL UNIQUE,
            EXECUTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
          )
        ';
      EXCEPTION
        WHEN OTHERS THEN
          IF SQLCODE != -955 THEN
            RAISE;
          END IF;
      END;
    `);

    await connection.commit();

    // Get already executed migrations
    const result = await connection.execute(`
      SELECT NAME
      FROM DB_MIGRATIONS
      ORDER BY ID
    `);

    const executedMigrations = new Set(
      result.rows.map((row) => row[0])
    );

    // Read migration files
    if (!fs.existsSync(migrationsDir)) {
      console.log("⚠️ Migration folder does not exist:");
      console.log(migrationsDir);
      return;
    }

    const migrationFiles = fs
      .readdirSync(migrationsDir)
      .filter((file) => file.endsWith(".sql"))
      .sort();

    if (migrationFiles.length === 0) {
      console.log("ℹ️ No migration files found.");
      return;
    }

    // Run migrations
    for (const file of migrationFiles) {
      if (executedMigrations.has(file)) {
        console.log(`✓ Already executed: ${file}`);
        continue;
      }

      console.log(`🚀 Running migration: ${file}`);

      const filePath = path.join(migrationsDir, file);

      const sql = fs.readFileSync(filePath, "utf8").trim();

      if (!sql) {
        console.log(`⚠️ Skipping empty migration: ${file}`);
        continue;
      }

      await connection.execute(sql);

      await connection.execute(
        `
          INSERT INTO DB_MIGRATIONS (NAME)
          VALUES (:name)
        `,
        {
          name: file,
        }
      );

      await connection.commit();

      console.log(`✅ Completed: ${file}`);
    }

    console.log("🎉 All migrations completed successfully.");
  } catch (error) {
    if (connection) {
      try {
        await connection.rollback();
      } catch (rollbackError) {
        console.error("Rollback failed:", rollbackError.message);
      }
    }

    console.error("❌ Migration failed:");
    console.error(error);

    process.exitCode = 1;
  } finally {
    if (connection) {
      try {
        await connection.close();
        console.log("🔌 Database connection closed");
      } catch (error) {
        console.error("Error closing connection:", error.message);
      }
    }
  }
}

migrate();